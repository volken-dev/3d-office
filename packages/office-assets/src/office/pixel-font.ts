/**
 * The rows of a character's glyph. A space is blank; any other character the font lacks throws, so
 * a typo in a stencil or board label fails the build instead of leaving a gap.
 */
export function glyphRows(character: string): readonly string[] {
  if (character === " ") return []
  if (!Object.hasOwn(PIXEL_FONT, character)) {
    throw new Error(`pixel font has no glyph '${character}' (add it to PIXEL_FONT)`)
  }
  return PIXEL_FONT[character]
}
